def _banner(entry: DocEntry) -> str:
    """The provenance header prepended to a copied artifact."""
    lines = [
        GENERATED_MARKER,
        f"<!-- source: {entry.source} -->",
        "",
    ]
    if entry.draft:
        lines += [DRAFT_BADGE, ""]
    lines += [
        '!!! info "Copied verbatim from the repository"',
        "",
        f"    Source: `{entry.source}`",
        "",
        f"    {entry.note}",
        "",
        "    Refresh with `python scripts/build_site.py`. Nothing on this page is",
        "    retyped, rounded or reformatted; every figure came from an executed",
        "    model call.",
        "",
    ]
    return "\n".join(lines)


def _insert_after_h1(body: str, block: str) -> str:
    """Put ``block`` just after the document's first H1 so the page title survives."""
    lines = body.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("# "):
            return "\n".join(lines[: i + 1] + ["", *block.splitlines(), *lines[i + 1 :]])
    # No H1: prepend, and let the nav title carry the page.
    return block + "\n" + body


def copy_docs(verbose: bool = True) -> list[str]:
    """Copy every whitelisted markdown artifact. Idempotent."""
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    copied: list[str] = []
    for entry in DOC_WHITELIST:
        src = REPO / entry.source
        if not src.is_file():
            raise SystemExit(
                f"build_site: whitelisted artifact is missing: {entry.source}\n"
                "  Run `python cli.py e2e --mode replay` to regenerate it. This script "
                "will not publish a page for an artifact that does not exist."
            )
        dest = RESULTS_DIR / entry.dest
        body = src.read_text(encoding="utf-8")
        out = _insert_after_h1(body, _banner(entry)).rstrip() + "\n"
        previous = dest.read_text(encoding="utf-8") if dest.is_file() else None
        dest.write_text(out, encoding="utf-8")
        state = "unchanged" if previous == out else "written"
        copied.append(entry.dest)
        if verbose:
            print(f"  doc    {entry.source:<48} -> site_src/results/{entry.dest}  [{state}]")
    return copied


def _notebook_images(path: Path) -> list[tuple[str, bytes]]:
    """Every image output in a notebook, in cell order, as (mime, bytes)."""
    nb = json.loads(path.read_text(encoding="utf-8"))
    images: list[tuple[str, bytes]] = []
    for cell in nb.get("cells", []):
        for output in cell.get("outputs", []):
            for mime, payload in (output.get("data") or {}).items():
                if mime.startswith("image/"):
                    if isinstance(payload, list):
                        payload = "".join(payload)
                    images.append((mime, base64.b64decode(payload)))
    return images


def copy_charts(verbose: bool = True) -> list[ChartEntry]:
    """Extract whitelisted notebook charts and (re)write results/charts.md."""
    CHARTS_DIR.mkdir(parents=True, exist_ok=True)
    published: list[ChartEntry] = []

    cache: dict[str, list[tuple[str, bytes]]] = {}
    for chart in CHART_WHITELIST:
        nb_path = REPO / chart.notebook
        if not nb_path.is_file():
            raise SystemExit(
                f"build_site: whitelisted notebook is missing: {chart.notebook}\n"
                "  Execute the notebooks (see REFRESH.md) before refreshing the site."
            )
        images = cache.setdefault(chart.notebook, _notebook_images(nb_path))
        if chart.index >= len(images):
            raise SystemExit(
                f"build_site: {chart.notebook} has {len(images)} image output(s); "
                f"the whitelist asks for index {chart.index}.\n"
                "  The notebook's chart order changed. Re-curate CHART_WHITELIST "
                "rather than guessing — a chart published under the wrong caption is "
                "a fabricated result."
            )
        _, data = images[chart.index]
        dest = CHARTS_DIR / chart.dest
        previous = dest.read_bytes() if dest.is_file() else None
        dest.write_bytes(data)
        state = "unchanged" if previous == data else "written"
        published.append(chart)
        if verbose:
            print(
                f"  chart  {chart.notebook.split('/')[-1]}[{chart.index}]"
                f" -> site_src/results/charts/{chart.dest}  [{state}]"
            )

    page = _charts_page(published)
    charts_md = RESULTS_DIR / "charts.md"
    previous_md = charts_md.read_text(encoding="utf-8") if charts_md.is_file() else None
    charts_md.write_text(page, encoding="utf-8")
    if verbose:
        state = "unchanged" if previous_md == page else "written"
        print(f"  page   (generated){'':<37} -> site_src/results/charts.md  [{state}]")
        for notebook, index, reason in EXCLUDED_CHARTS:
            head = f"  skip   {notebook.split('/')[-1]}[{index}]"
            print(head)
            print(textwrap.fill(reason, width=88, initial_indent=" " * 9, subsequent_indent=" " * 9))
    return published


def _charts_page(charts: list[ChartEntry]) -> str:
    parts = [
        GENERATED_MARKER,
        "<!-- source: artifacts/notebooks/*.out.ipynb via CHART_WHITELIST -->",
        "",
        "# Charts",
        "",
        DRAFT_BADGE,
        "",
        "Interval charts exported from the two executed notebooks. Each shows point",
        "estimates with 95% bootstrap CIs (10,000 resamples, seed `20260812`) and the",
        "relevant gate bound. Gates are decided on the CI bound, not on the point.",
        "",
    ]
    for chart in charts:
        parts += [
            f"## {chart.title}",
            "",
            f"![{chart.title}](charts/{chart.dest})",
            "",
            chart.caption,
            "",
        ]
    parts += [
        "## Charts deliberately not published",
        "",
        "A chart is excluded here rather than quietly dropped, so the exclusion is",
        "reviewable. Each is re-checked whenever the notebooks are re-executed.",
        "",
    ]
    for notebook, index, reason in EXCLUDED_CHARTS:
        parts += [f"- **`{notebook}` image {index}** — {reason}", ""]
    parts += [
        "---",
        "",
        "*Regenerate: execute the notebooks, then `python scripts/build_site.py`.*",
        "",
    ]
    return "\n".join(parts)


