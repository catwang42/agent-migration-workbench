def build_site(site_dir: Path, verbose: bool = True) -> None:
    cmd = [sys.executable, "-m", "mkdocs", "build", "--strict", "--site-dir", str(site_dir)]
    if verbose:
        print(f"\n$ {' '.join(cmd)}")
    result = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True)
    if result.stdout.strip():
        print(result.stdout.rstrip())
    if result.stderr.strip():
        print(result.stderr.rstrip())
    if result.returncode != 0:
        raise SystemExit(f"build_site: mkdocs build --strict failed ({result.returncode}).")


@dataclass
class Hit:
    origin: str
    phrase: str
    files: list[str] = field(default_factory=list)


def check_forbidden(root: Path, verbose: bool = True) -> list[Hit]:
    """Grep every text file under ``root`` for internal content. Returns hits."""
    if not root.is_dir():
        raise SystemExit(f"build_site: nothing to check — {root} is not a directory.")

    targets = [
        p
        for p in sorted(root.rglob("*"))
        if p.is_file() and p.suffix.lower() in {".html", ".htm", ".md", ".txt", ".json", ".xml"}
    ]
    # The search index duplicates page text; excluding it would let a leak hide
    # in search results, so it stays in.
    excuses: dict[str, list[str]] = {}
    for excuse in ALLOWLIST:
        excuses.setdefault(_normalise(excuse.phrase), []).append(_normalise(excuse.context))

    hits: dict[tuple[str, str], Hit] = {}
    scanned = 0
    excused = 0
    for path in targets:
        try:
            text = _normalise(path.read_text(encoding="utf-8"))
        except (UnicodeDecodeError, OSError):
            continue
        scanned += 1
        rel = str(path.relative_to(root))
        for forbidden in FORBIDDEN:
            for phrase in forbidden.phrases:
                needle = _normalise(phrase)
                contexts = excuses.get(needle, [])
                start = text.find(needle)
                while start != -1:
                    window = text[max(0, start - WINDOW) : start + len(needle) + WINDOW]
                    if any(context in window for context in contexts):
                        excused += 1
                    else:
                        key = (forbidden.origin, phrase)
                        hits.setdefault(key, Hit(forbidden.origin, phrase)).files.append(rel)
                        break  # one report per phrase per file is enough
                    start = text.find(needle, start + len(needle))

    if verbose:
        phrase_count = sum(len(f.phrases) for f in FORBIDDEN)
        print(
            f"\nForbidden-content check: {phrase_count} phrase(s) from "
            f"{len(FORBIDDEN)} source(s) against {scanned} built file(s) under {root}."
        )
        if excused:
            print(
                f"  {excused} occurrence(s) excused in context by ALLOWLIST "
                f"({len(ALLOWLIST)} entr(y/ies))."
            )
    return list(hits.values())


def report_hits(hits: list[Hit]) -> int:
    if not hits:
        print("  PASS — no internal content found in the built site.")
        return 0
    print("  FAIL — internal content reached the built site:\n")
    by_origin: dict[str, list[Hit]] = {}
    for hit in hits:
        by_origin.setdefault(hit.origin, []).append(hit)
    for origin, group in by_origin.items():
        print(f"  {origin}")
        for hit in group:
            files = ", ".join(sorted(set(hit.files))[:6])
            more = "" if len(set(hit.files)) <= 6 else f" (+{len(set(hit.files)) - 6} more)"
            print(f"    {hit.phrase!r} in {files}{more}")
        print()
    print(
        "  This site is customer-facing. Remove the content, or — if the phrase is\n"
        "  genuinely legitimate here — add it to ALLOWLIST in this file with a reason."
    )
    return 1


# --------------------------------------------------------------------------- #


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--no-build",
        action="store_true",
        help="skip mkdocs; run the leak check against site_src/ sources instead",
    )
    parser.add_argument(
        "--check-only",
        action="store_true",
        help="do not copy anything; only build and check",
    )
    parser.add_argument(
        "--site-dir",
        type=Path,
        default=None,
        help="check this already-built directory instead of building one",
    )
    args = parser.parse_args(argv)

    print(f"build_site: repo {REPO}")
    print(f"build_site: docs_dir is site_src/ — docs/ is internal and is never published.\n")

    if not args.check_only:
        print("Copying whitelisted artifacts:")
        copy_docs()
        copy_charts()

    if args.site_dir is not None:
        hits = check_forbidden(args.site_dir)
        return report_hits(hits)

    if args.no_build:
        print("\n--no-build: checking site_src/ sources rather than built output.")
        return report_hits(check_forbidden(SITE_SRC))

    with tempfile.TemporaryDirectory(prefix="amw-site-") as tmp:
        built = Path(tmp) / "site"
        build_site(built)
        hits = check_forbidden(built)
        status = report_hits(hits)

    if status == 0:
        print(
            "\nNext: a human runs `mkdocs gh-deploy --strict` to publish.\n"
            "This script never deploys."
        )
    return status


if __name__ == "__main__":
    raise SystemExit(main())
