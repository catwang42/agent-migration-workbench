def _notebook_images(path: Path) -> list[tuple[str, bytes]]:
    """Every image output in a notebook, in cell order, as (mime, bytes)."""
    nb = json.loads(path.read_text(encoding="utf-8"))
    images: list[tuple[str, bytes]] = []
    for cell in nb.get("cells", []):
        for output in cell.get("outputs", []):
            for mime, payload in (output.get("data") or {}).items():
                if mime.startswith("image/"):
                    if isinstance(payload, list):
                        payload = "".join(payload)
                    images.append((mime, base64.b64decode(payload)))
    return images


def copy_charts(verbose: bool = True) -> list[ChartEntry]:
    """Extract whitelisted notebook charts and (re)write results/charts.md."""
    CHARTS_DIR.mkdir(parents=True, exist_ok=True)
    published: list[ChartEntry] = []

    cache: dict[str, list[tuple[str, bytes]]] = {}
    for chart in CHART_WHITELIST:
        nb_path = REPO / chart.notebook
        if not nb_path.is_file():
            raise SystemExit(
                f"build_site: whitelisted notebook is missing: {chart.notebook}\n"
                "  Execute the notebooks (see REFRESH.md) before refreshing the site."
            )
        images = cache.setdefault(chart.notebook, _notebook_images(nb_path))
        if chart.index >= len(images):
            raise SystemExit(
                f"build_site: {chart.notebook} has {len(images)} image output(s); "
                f"the whitelist asks for index {chart.index}.\n"
                "  The notebook's chart order changed. Re-curate CHART_WHITELIST "
                "rather than guessing — a chart published under the wrong caption is "
                "a fabricated result."
            )
        _, data = images[chart.index]
        dest = CHARTS_DIR / chart.dest
        previous = dest.read_bytes() if dest.is_file() else None
        dest.write_bytes(data)
        state = "unchanged" if previous == data else "written"
        published.append(chart)
        if verbose:
            print(
                f"  chart  {chart.notebook.split('/')[-1]}[{chart.index}]"
                f" -> site_src/results/charts/{chart.dest}  [{state}]"
            )

    page = _charts_page(published)
    charts_md = RESULTS_DIR / "charts.md"
    previous_md = charts_md.read_text(encoding="utf-8") if charts_md.is_file() else None
    charts_md.write_text(page, encoding="utf-8")
    if verbose:
        state = "unchanged" if previous_md == page else "written"
        print(f"  page   (generated){'':<37} -> site_src/results/charts.md  [{state}]")
        for notebook, index, reason in EXCLUDED_CHARTS:
            head = f"  skip   {notebook.split('/')[-1]}[{index}]"
            print(head)
            print(textwrap.fill(reason, width=88, initial_indent=" " * 9, subsequent_indent=" " * 9))
    return published


