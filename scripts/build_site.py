@dataclass(frozen=True)
class Excuse:
    """One occurrence of a forbidden phrase that is legitimate *in context*.

    An excuse is deliberately **not** a blanket suppression of the phrase. It
    excuses only those occurrences that appear within :data:`WINDOW` characters of
    ``context``. The same phrase used anywhere else on the site still fails, which
    is the whole point: "zero quality drop" is legitimate in the sentence that
    forbids it and illegitimate everywhere else.
    """

    phrase: str
    context: str
    reason: str


#: How much text either side of a hit is searched for the excusing context.
WINDOW = 200

#: Kept tiny on purpose — an allowlist that grows is a leak check that has stopped
#: working. Every entry needs a reason.
ALLOWLIST: tuple[Excuse, ...] = (
    Excuse(
        phrase="zero quality drop",
        context="never zero quality drop",
        reason=(
            "The scorecard's own parity-language disclaimer, copied verbatim from "
            "artifacts/results/scorecard_widened.md: 'a passing gate licenses "
            '"quality parity within measurement under pre-agreed gates" — never '
            "\"zero quality drop\"'. The report disavowing the phrase is exactly the "
            "wording CLAUDE.md ground rule 7 asks for. Any other occurrence still fails."
        ),
    ),
    Excuse(
        phrase="zero quality drop",
        context="the reports never say &quot;zero quality drop&quot;",
        reason=(
            "config/gates.yaml's own header comment, embedded into module 03 by "
            "pymdownx.snippets so the page cannot drift from the file. The line is the "
            "gates file forbidding the phrase — the same disavowal the scorecard makes, "
            "in the source of truth rather than the report. Matching on the escaped "
            "'the reports never say' prefix keeps this narrow: a page that used the "
            "phrase as a claim would not carry it."
        ),
    ),
)


_WS = re.compile(r"\s+")
#: Quote marks and the punctuation the theme reflows around are stripped before
#: matching, so a phrase still matches whether it was rendered straight, curly, as
#: an HTML entity, or wrapped in markup. Backslashes go too: the search index is
#: JSON, where the same sentence arrives as `never \"zero quality drop\"`, and a
#: phrase must not escape the check merely by being escaped.
_NOISE = re.compile(r"[\"'`‘’“”\\]|&quot;|&#3[49];|&rsquo;|&ldquo;|&rdquo;")
#: Every dash, ASCII or typographic, becomes a space, so "75-90%" and "75–90%"
#: normalise alike and a phrase cannot slip through on hyphenation alone.
_DASH = re.compile(r"[-‐-―]|&mdash;|&ndash;")


def _normalise(text: str) -> str:
    """Lowercase, strip quoting noise, and collapse whitespace and dashes.

    The point is that a phrase survives the trip through Markdown and the theme:
    rewrapped lines, smart quotes, entity-escaped quotes and em dashes all
    normalise to the same string the whitelist was written in.
    """
    text = _NOISE.sub("", text.lower())
    text = _DASH.sub(" ", text)
    return _WS.sub(" ", text).strip()


