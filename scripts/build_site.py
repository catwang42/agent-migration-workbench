#!/usr/bin/env python3
"""Refresh the public workshop companion's Results section, then prove it is clean.

Two jobs, in this order:

1. **Copy an explicit WHITELIST** of repository artifacts into ``site_src/results/``
   so that refreshing the published site after the final run is one command. Only
   files named in :data:`DOC_WHITELIST` and :data:`CHART_WHITELIST` are ever
   copied. There is no glob over ``artifacts/`` and no glob over ``docs/``.

2. **Grep the BUILT output for leaks.** ``docs/`` holds internal presenter
   material — objection handling, the master plan, the build plan, the spike log,
   the runbook talk track — none of which may reach a customer-facing site. The
   check looks for distinctive *phrases* from each of those files rather than
   filenames, because the failure mode that matters is content pasted into a page,
   not a file copied by name. A hit exits non-zero.

The published site's ``docs_dir`` is ``site_src``, never ``docs/`` (see
``mkdocs.yml``). This script is the second line of defence behind that setting.

Usage
-----
    python scripts/build_site.py                # copy, then build to a temp dir and check
    python scripts/build_site.py --no-build     # copy and check site_src/ sources only
    python scripts/build_site.py --check-only   # no copying; build + check
    python scripts/build_site.py --site-dir DIR # check an already-built directory

Ground rules this script exists to keep (CLAUDE.md):
  1. No fabricated results — artifacts are copied byte-for-byte from the repo. The
     only thing added is a banner naming the source file and its provenance.
  3. Prices only from config/pricing.yaml — nothing here computes or writes a price.
"""

